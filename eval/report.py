"""Write the generated numbers block of docs/results.md from eval/results/waypoint-test.json.

    uv run python -m eval.report

Everything between the BEGIN and END markers in docs/results.md is replaced; the prose around it
is hand-written and must not quote numbers that are not in this block.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULT = ROOT / "eval" / "results" / "waypoint-test.json"
DOC = ROOT / "docs" / "results.md"
BEGIN = "<!-- BEGIN generated by eval/report.py -->"
END = "<!-- END generated by eval/report.py -->"


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def block(r: dict) -> str:
    h = r["headline"]
    lines = [
        BEGIN,
        "",
        f"Dataset: {r['dataset']}. {r['eval_tasks']:,} held-out test tasks, "
        f"{r['train_stream']:,} training runs fed back, k = {r['k']}. "
        f"Generated {r['generated_at']}.",
        "",
        "| Router | Completeness@5 | Recall@5 |",
        "|---|---|---|",
        f"| Stateless BM25 tool search (baseline) | {pct(h['baseline'])} | "
        f"{pct(h['recall5_baseline'])} |",
        f"| Flat memory: copy the nearest past run's tools | {pct(h['flat_memory'])} | "
        f"{pct(r['curve'][-1]['flat_memory']['recall'])} |",
        f"| Flat k-NN memory: Waypoint's weights and candidate budget over whole past runs | "
        f"{pct(h['flat_knn'])} | {pct(r['curve'][-1]['flat_knn']['recall'])} |",
        f"| **Waypoint** (experience graph in HydraDB) | **{pct(h['waypoint'])}** | "
        f"**{pct(h['recall5_waypoint'])}** |",
        "",
        "Learning curve (Completeness@5 on the same held-out tasks after each batch of runs):",
        "",
        "| Runs fed back | BM25 | Flat memory | Flat k-NN | Waypoint |",
        "|---|---|---|---|---|",
    ]
    for p in r["curve"]:
        lines.append(
            f"| {p['runs']:,} | {pct(p['bm25']['completeness'])} | "
            f"{pct(p['flat_memory']['completeness'])} | {pct(p['flat_knn']['completeness'])} | "
            f"{pct(p['waypoint']['completeness'])} |"
        )
    lines += [
        "",
        "Slices at the end of the stream (Completeness@5):",
        "",
        "| Slice | Tasks | BM25 | Flat memory | Flat k-NN | Waypoint |",
        "|---|---|---|---|---|---|",
    ]
    names = {
        "seen_toolset": "Tool set seen in training",
        "novel_toolset": "Tool set never seen in training",
    }
    for key, s in r["slices"].items():
        lines.append(
            f"| {names.get(key, key)} | {s['n']:,} | {pct(s['bm25'])} | "
            f"{pct(s['flat_memory'])} | {pct(s['flat_knn'])} | {pct(s['waypoint'])} |"
        )
    lines += [
        "",
        f"Context cost: Waypoint loads {h['tokens_per_task_waypoint']:,} tool-schema tokens per "
        f"task on average, against {h['tokens_catalog']:,} for the whole catalog "
        f"({h['tokens_catalog'] / h['tokens_per_task_waypoint']:.0f}x fewer).",
        "",
        f"Route latency during the eval, 8 concurrent clients against one HydraDB node: "
        f"p50 {h['latency_p50_ms']} ms, p95 {h['latency_p95_ms']} ms.",
        "",
        END,
    ]
    return "\n".join(lines)


def main() -> None:
    r = json.loads(RESULT.read_text())
    doc = DOC.read_text()
    start, end = doc.index(BEGIN), doc.index(END) + len(END)
    DOC.write_text(doc[:start] + block(r) + doc[end:])


if __name__ == "__main__":
    main()
